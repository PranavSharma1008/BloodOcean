export const getStates = () => Object.keys(STATES_AND_DISTRICTS);

export const getDistricts = (state) => STATES_AND_DISTRICTS[state] || [];

export const normalizeDistrict = (state, value) => {
  if (!state || !value) return value || '';
  const match = getDistricts(state).find(
    (district) => district.toLowerCase() === value.toLowerCase()
  );
  return match || value;
};

export const getTranslatedState = (state, lang) => {
  if (lang === 'hi' && HINDI_STATE_NAMES[state]) return HINDI_STATE_NAMES[state];
  return state;
};

export const getTranslatedDistrict = (district, lang) => {
  if (lang === 'hi' && HINDI_DISTRICT_NAMES[district]) return HINDI_DISTRICT_NAMES[district];
  return district;
};
